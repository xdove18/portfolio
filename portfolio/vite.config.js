import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

/* ============================================================
   НАСТРОЙКИ СБОРЩИКА
   ============================================================
   Здесь всего одна вещь, которую вам может понадобиться
   поменять — строка BASE чуть ниже.
   ============================================================ */

/* ------------------------------------------------------------
   ГДЕ БУДЕТ ЛЕЖАТЬ САЙТ
   ------------------------------------------------------------
   Впишите один из двух вариантов:

   "/portfolio/"  — сайт открывается по адресу
                    xdove18.github.io/portfolio/
                    То есть во вложенной папке. Так работает
                    GitHub Pages, пока не подключён свой домен.
                    Название папки должно совпадать с названием
                    репозитория на гитхабе.

   "/"            — сайт лежит в корне адреса. Так будет, когда
                    вы подключите свой домен (например
                    lizaivanova.ru) — тогда впишите сюда "/"
                    и залейте изменения на гитхаб.

   Если ошибиться, сайт откроется белым экраном: браузер будет
   искать стили и картинки не по тому адресу.
   ------------------------------------------------------------ */
const BASE = "/";

/* ------------------------------------------------------------
   АДРЕС САЙТА
   ------------------------------------------------------------
   Полный адрес с https:// и без косой черты на конце.
   Нужен поисковикам и соцсетям: в превью ссылки и в карте
   сайта адреса обязаны быть полными.

   Если домен поменяется — впишите новый здесь и в двух местах
   рядом: public/robots.txt и index.html (строки canonical
   и og:url).
   ------------------------------------------------------------ */
const АДРЕС = "https://xdovee.ru";

/* ------------------------------------------------------------
   ЗАПАСНАЯ СТРАНИЦА ДЛЯ ПРЯМЫХ ССЫЛОК
   ------------------------------------------------------------
   Страницы кейсов существуют только внутри сайта, отдельных
   файлов для них нет. Если человек откроет ссылку
   .../projects/habits напрямую или обновит страницу,
   GitHub Pages такого файла не найдёт.

   Хитрость: когда файла нет, Pages показывает страницу
   404.html. Мы кладём туда точную копию главной — сайт
   запускается, смотрит на адрес в строке браузера и открывает
   нужный кейс. Человек ничего не замечает.

   Копия делается сама при каждой сборке.
   ------------------------------------------------------------ */
function копияДляПрямыхСсылок() {
  return {
    name: "копия-404",
    closeBundle() {
      const папка = resolve(import.meta.dirname, "dist");
      copyFileSync(resolve(папка, "index.html"), resolve(папка, "404.html"));
    },
  };
}

/* ============================================================
   СТРАНИЦЫ ДЛЯ ПОИСКОВИКОВ
   ============================================================
   Зачем это нужно.

   Сайт — одно приложение: все кейсы рисует один и тот же файл
   index.html. Для человека это незаметно, а для поисковика
   плохо сразу по трём причинам:

     1. Файла /projects/veles на сервере нет, поэтому GitHub
        Pages отвечает «страница не найдена» (код 404). Робот
        верит и в поиск кейс не берёт.
     2. Заголовок и описание у всех страниц одинаковые — те,
        что в index.html. Свои заголовки подставляет уже сам
        сайт, но робот соцсети до этого не доживает.
     3. Ссылка на кейс в Telegram или ВКонтакте превьюсится
        как главная: то же название, то же фото.

   Что делает этот кусок. После сборки он раскладывает рядом
   с главной по отдельному файлу на каждый кейс:

     dist/projects/veles/index.html
     dist/projects/agency-crm/index.html   и так далее

   Внутри — та же главная, но с подменённым заголовком,
   описанием, адресом и картинкой превью. Теперь адрес
   существует по-настоящему: сервер отдаёт его с кодом 200,
   а в превью видно название кейса и его обложку.

   Заодно пишется карта сайта sitemap.xml — список всех
   адресов для поисковика.

   Тексты берутся прямо из src/data/projects.js, поэтому
   отдельно их править не нужно: добавили кейс — он сам
   появится и в файлах, и в карте сайта.
   ============================================================ */

/* Описание для поисковика: из текста кейса убираем пометки
   разметки (** жирный ** и == маркер ==) и обрезаем примерно
   до 160 знаков — длиннее поисковик всё равно не покажет.
   Обрезаем по границе слова, а не посреди него. */
function короткоеОписание(текст, предел = 160) {
  const чистый = String(текст || "")
    .replace(/\*\*/g, "")
    .replace(/==/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (чистый.length <= предел) return чистый;
  const кусок = чистый.slice(0, предел);
  const пробел = кусок.lastIndexOf(" ");
  return (пробел > 80 ? кусок.slice(0, пробел) : кусок).replace(/[.,;:—-]+$/, "") + "…";
}

/* В значение атрибута нельзя класть кавычки и угловые скобки
   как есть — иначе разметка сломается. */
function дляАтрибута(текст) {
  return String(текст)
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function страницыДляПоисковиков() {
  return {
    name: "страницы-для-поисковиков",

    /* enforce: "post" и порядок плагинов ниже важны: эта
       работа должна идти после того, как копия-404 сделана,
       иначе 404.html получится из уже изменённого файла. */
    async closeBundle() {
      const корень = import.meta.dirname;
      const папка = resolve(корень, "dist");

      /* Тексты кейсов берём из того же файла, который читает
         сайт. pathToFileURL нужен на Windows: там путь вида
         C:\... сам по себе адресом не считается. */
      const { projects } = await import(
        pathToFileURL(resolve(корень, "src/data/projects.js")).href
      );
      const { site } = await import(
        pathToFileURL(resolve(корень, "src/data/site.js")).href
      );

      const главная = readFileSync(resolve(папка, "index.html"), "utf8");

      /* Кейсы-заглушки («скоро») пропускаем: такой страницы
         на сайте нет, и в поиске ей делать нечего. */
      const кейсы = projects.filter((кейс) => !кейс.comingSoon);

      for (const кейс of кейсы) {
        const адрес = `${АДРЕС}/projects/${кейс.slug}`;
        const заголовок = `${кейс.title} — кейс ${site.name}`;
        const описание = короткоеОписание(кейс.intro);

        /* Картинка превью ссылки. Соцсети обрезают её под
           широкий прямоугольник, поэтому вертикальный снимок
           телефона в превью выглядит плохо. Если у кейса нет
           ничего широкого — положите картинку 1200×630 и
           впишите её в поле ogImage в projects.js. */
        const картинка =
          кейс.ogImage || кейс.heroImage || кейс.cover?.[0] || "/images/me.webp";

        let страница = главная
          .replace(
            /<title>[\s\S]*?<\/title>/,
            `<title>${дляАтрибута(заголовок)}</title>`
          )
          .replace(
            /(<meta\s+name="description"\s+content=")[\s\S]*?(")/,
            `$1${дляАтрибута(описание)}$2`
          )
          .replace(
            /(<link rel="canonical" href=")[^"]*(")/,
            `$1${адрес}$2`
          )
          .replace(
            /(<meta property="og:url" content=")[^"]*(")/,
            `$1${адрес}$2`
          )
          .replace(
            /(<meta property="og:title" content=")[^"]*(")/,
            `$1${дляАтрибута(`${кейс.title} — ${кейс.tagline}`)}$2`
          )
          .replace(
            /(<meta\s+property="og:description"\s+content=")[\s\S]*?(")/,
            `$1${дляАтрибута(описание)}$2`
          )
          .replace(
            /(<meta\s+property="og:image"\s+content=")[\s\S]*?(")/,
            `$1${АДРЕС}${картинка}$2`
          )
          /* Тип превью: главная — сайт, кейс — статья */
          .replace(
            /(<meta property="og:type" content=")[^"]*(")/,
            `$1article$2`
          );

        const куда = resolve(папка, "projects", кейс.slug);
        mkdirSync(куда, { recursive: true });
        writeFileSync(resolve(куда, "index.html"), страница, "utf8");
      }

      /* ---------- КАРТА САЙТА ----------
         Простой список адресов. lastmod — дата сборки: она
         подсказывает поисковику, что страницу стоит перечитать.
         priority — что на сайте главнее; у главной 1. */
      const сегодня = new Date().toISOString().slice(0, 10);
      const адреса = [
        { loc: `${АДРЕС}/`, priority: "1.0" },
        ...кейсы.map((кейс) => ({
          loc: `${АДРЕС}/projects/${кейс.slug}`,
          priority: "0.8",
        })),
      ];

      const карта =
        '<?xml version="1.0" encoding="UTF-8"?>\n' +
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
        адреса
          .map(
            ({ loc, priority }) =>
              `  <url>\n    <loc>${loc}</loc>\n` +
              `    <lastmod>${сегодня}</lastmod>\n` +
              `    <priority>${priority}</priority>\n  </url>`
          )
          .join("\n") +
        "\n</urlset>\n";

      writeFileSync(resolve(папка, "sitemap.xml"), карта, "utf8");

      console.log(
        `\nСтраницы для поисковиков: ${кейсы.length} кейса + карта сайта`
      );
    },
  };
}

export default defineConfig({
  base: BASE,

  /* Порядок важен: сначала делается копия 404.html с чистой
     главной, и только потом раскладываются страницы кейсов. */
  plugins: [react(), копияДляПрямыхСсылок(), страницыДляПоисковиков()],

  build: {
    /* Мелкие файлы сборщик по умолчанию «вшивает» прямо в
       стили, чтобы сэкономить одно обращение к серверу.
       Для шрифтов это вредно: вшитый шрифт грузится вместе со
       стилями всегда, даже если его буквы на странице не
       встретятся, и браузер не может сохранить его в кэш
       отдельно. Поэтому шрифты всегда оставляем файлами. */
    assetsInlineLimit(путь) {
      if (путь.endsWith(".woff2")) return false;
      return undefined;   // для остальных файлов — как обычно
    },
  },

  /* Порт — это «дверь», через которую браузер стучится к сайту,
     когда вы запускаете его у себя на компьютере.
     Здесь номер намеренно не задан: если 5173 занята другой
     программой, Vite спокойно возьмёт соседнюю. */
  server: {
    port: process.env.PORT ? Number(process.env.PORT) : undefined,
    strictPort: false,
  },
});
