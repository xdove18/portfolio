import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

/* ============================================================
   НАСТРОЙКИ СБОРЩИКА
   ============================================================
   Обычно этот файл трогать не нужно.

   Единственное, что настроено вручную — номер порта.
   Порт это «дверь», через которую браузер стучится к сайту.

   Здесь номер НЕ задан жёстко специально:
   • если снаружи передали номер двери — берём его;
   • если нет — Vite сам возьмёт свободную (обычно 5173,
     а если она занята, то следующую).

   Благодаря этому сайт запускается, даже когда 5173 уже
   занята другой программой.
   ============================================================ */

export default defineConfig({
  plugins: [react()],

  server: {
    // undefined = «решай сам»
    port: process.env.PORT ? Number(process.env.PORT) : undefined,
    // false = если дверь занята, спокойно взять соседнюю
    strictPort: false,
  },
});
