import { useEffect, useState } from "react";
import { прочитатьСогласие, записатьСогласие } from "../../utils/consent";
import { загрузитьМетрику } from "../../utils/metrika";
import { fixHangingWords } from "../../utils/typography";
import s from "./CookieBanner.module.css";

/* ============================================================
   БАННЕР ПРО КУКИ
   ============================================================
   По российскому закону сайт обязан предупредить человека
   о сборе данных и спросить разрешение ДО того, как начнёт
   их собирать. Поэтому здесь важен порядок: сначала баннер,
   и только после нажатия «Принять» загружается Яндекс Метрика.

   Пока человек не ответил, никакой аналитики на сайте нет —
   ни одного запроса к Яндексу, ни одной его куки.

   Ответ запоминается, и второй раз баннер не появляется.
   ============================================================ */

export default function CookieBanner() {
  /* null — ещё не знаем, что ответил человек. В этот момент
     баннер не рисуем: иначе он мигнёт на долю секунды у тех,
     кто уже согласился. */
  const [ответ, setОтвет] = useState(null);

  useEffect(() => {
    const сохранённый = прочитатьСогласие();
    setОтвет(сохранённый ?? "спросить");

    // Согласие уже есть — подключаем аналитику сразу
    if (сохранённый === "yes") загрузитьМетрику();
  }, []);

  function решить(выбор) {
    записатьСогласие(выбор);
    setОтвет(выбор);

    if (выбор === "yes") загрузитьМетрику();
  }

  if (ответ !== "спросить") return null;

  return (
    <div className={s.banner} role="dialog" aria-label="Использование куки">
      <p className={s.text}>
        {fixHangingWords(
          "Сайт использует куки и сервис Яндекс Метрика, чтобы понимать, какие кейсы читают и откуда приходят люди. Данные обезличены и нужны только для статистики посещений."
        )}
      </p>

      <div className={s.buttons}>
        <button
          type="button"
          className={s.accept}
          onClick={() => решить("yes")}
        >
          Принять
        </button>

        <button
          type="button"
          className={s.decline}
          onClick={() => решить("no")}
        >
          {fixHangingWords("Только необходимые")}
        </button>
      </div>
    </div>
  );
}
