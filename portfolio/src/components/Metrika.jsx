import { useEffect, useRef } from "react";
import { useLocation } from "react-router-dom";

/* ============================================================
   ЯНДЕКС МЕТРИКА: УЧЁТ ПЕРЕХОДОВ ВНУТРИ САЙТА
   ============================================================
   Сам счётчик подключён в файле index.html — он считает первый
   заход. Этот компонент нужен для всего, что происходит дальше.

   Дело вот в чём. Обычный сайт при переходе на другую страницу
   перезагружается целиком, и счётчик срабатывает заново. Ваш
   сайт устроен иначе: он не перезагружается, а перерисовывает
   содержимое на месте — поэтому переходы такие быстрые.

   Для Метрики это значит, что после первого захода она больше
   ничего не заметит. Без этого компонента в статистике был бы
   виден только тот раздел, с которого человек начал, а все
   переходы по кейсам не попали бы в отчёты вообще.

   Здесь мы сообщаем Метрике о каждом переходе сами.
   ============================================================ */

export default function Metrika() {
  const location = useLocation();

  /* Первый показ Метрика уже засчитала сама, когда загрузилась.
     Если сообщить о нём ещё раз, один заход посчитается дважды. */
  const первыйПоказ = useRef(true);

  // Откуда человек пришёл на текущую страницу — внутри сайта
  const предыдущийАдрес = useRef("");

  useEffect(() => {
    if (первыйПоказ.current) {
      первыйПоказ.current = false;
      предыдущийАдрес.current = window.location.href;
      return;
    }

    /* Небольшая задержка нужна, чтобы новая страница успела
       поменять заголовок вкладки: в отчётах Метрики страницы
       подписаны именно заголовками, и без паузы у всех кейсов
       был бы заголовок предыдущей страницы. */
    const таймер = setTimeout(() => {
      /* Счётчика может не быть: на вашем компьютере он выключен
         намеренно, а у посетителя его может заблокировать
         расширение-блокировщик. Это не ошибка — просто ничего
         не отправляем. */
      if (typeof window.ym !== "function") return;

      const адрес = window.location.href;

      window.ym(window.METRIKA_ID, "hit", адрес, {
        title: document.title,
        referer: предыдущийАдрес.current,
      });

      предыдущийАдрес.current = адрес;
    }, 120);

    return () => clearTimeout(таймер);
  }, [location]);

  return null; // компонент ничего не рисует, только считает переходы
}
