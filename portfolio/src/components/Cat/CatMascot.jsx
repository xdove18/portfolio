import { useEffect, useRef } from "react";
import { asset } from "../../utils/asset";
import s from "./CatMascot.module.css";

/* ============================================================
   КОШКА-МАСКОТ
   ============================================================
   Пиксельная кошка, которая сидит, моргает, шевелит ушами
   и хвостом. По нажатию — встаёт, разворачивается боком
   и либо уходит на несколько шагов, либо подпрыгивает.
   Потом садится обратно.

   Откуда взялась. Кадры и всё поведение — из вашего макета
   «Интерактивный маскот кошки». Числа ниже (сколько кадр
   держится, на сколько градусов поворачивается ухо) взяты
   оттуда как есть.

   ------------------------------------------------------------
   ГДЕ ОНА СТОИТ
   ------------------------------------------------------------
   Кошка занимает всю ширину того места, куда её поставили,
   и стоит на его нижнем краю. На главной это полоска над
   кнопкой «Написать в Telegram», в кейсе — низ боковой панели.

   Дальность прогулки и прыжка считается от ширины места:
   в узкой панели кошка гуляет на несколько шагов, в широкой —
   дальше. Если места нет совсем, прыжок получается на месте.

   ------------------------------------------------------------
   ПОЧЕМУ ЗДЕСЬ НЕТ useState
   ------------------------------------------------------------
   Картинка меняется 60 раз в секунду. Если каждый кадр
   обновлять состояние, React будет перерисовывать страницу
   без остановки и ноутбук начнёт шуметь. Поэтому кадры
   рисуются напрямую через ref — так делают все анимации.
   ============================================================ */

/* Размеры кадров и их «точка опоры» cx — это середина кошки
   по горизонтали. Кадр ставится так, чтобы cx оказался там,
   где кошка сейчас стоит. Числа из макета, менять не нужно. */
const КАДРЫ = {
  sit_0: { ш: 88, в: 135, cx: 40 },
  sit_3: { ш: 93, в: 124, cx: 47 },
  sit_4: { ш: 119, в: 115, cx: 60 },
  walk_0: { ш: 176, в: 125, cx: 86 },
  walk_1: { ш: 168, в: 117, cx: 84 },
  walk_2: { ш: 163, в: 115, cx: 80 },
  walk_3: { ш: 137, в: 114, cx: 71 },
  walk_4: { ш: 162, в: 117, cx: 78 },
  walk_5: { ш: 158, в: 119, cx: 77 },
  jump_0: { ш: 136, в: 93, cx: 65 },
  jump_1: { ш: 171, в: 91, cx: 70 },
  jump_2: { ш: 207, в: 87, cx: 97 },
  jump_3: { ш: 161, в: 85, cx: 70 },
  jump_4: { ш: 171, в: 85, cx: 70 },
  jump_5: { ш: 139, в: 85, cx: 60 },
};

/* Самый широкий кадр ходьбы и прыжка — по ним считаем,
   сколько места кошке нужно, чтобы не выехать за край */
const ШИРИНА_ХОДЬБЫ = 176;
const ШИРИНА_ПРЫЖКА = 207;

const плавно = (p) =>
  p < 0.5 ? 2 * p * p : 1 - Math.pow(-2 * p + 2, 2) / 2;

/* Сколько места остаётся кошке по бокам: ширина полоски
   минус сама кошка в самом широком кадре и небольшие поля.
   В узкой панели это десяток точек, в широкой — сотни. */
function поле(ширина, S, ширинаКадра) {
  return Math.max(0, Math.round((ширина - ширинаКадра * S) / 2) - 6);
}

/* Где кошка стоит, когда страница только открылась.
   Чуть правее середины — так она не делит полоску пополам.
   Если полоска узкая, место поджимается к тому, что есть. */
function начальноеМесто(ширина, S) {
  const п = поле(ширина, S, ШИРИНА_ХОДЬБЫ);
  const середина = ширина / 2;
  return Math.round(
    Math.min(Math.max(ширина * 0.68, середина - п), середина + п)
  );
}

export default function CatMascot({
  /* Масштаб кошки. 1 — родной размер кадров: пиксели
     ложатся один в один и картинка самая чёткая. */
  scale = 1,
  /* Насколько часто нажатие приводит к прыжку, а не к прогулке */
  jumpChance = 0.3,
  /* На сколько точек кошка уходит за одну прогулку.
     Если места меньше, прогулка сама укорачивается. */
  walkDistance = 260,
  /* Скорость ходьбы, точек в секунду */
  walkSpeed = 55,
  /* Подпись для экранного диктора */
  label = "Кошка-маскот. Нажмите, чтобы она прошлась",
}) {
  const сцена = useRef(null);
  const кошка = useRef(null);
  const тень = useRef(null);
  const каркас = useRef(null);
  const хвост = useRef(null);
  const ухоЛ = useRef(null);
  const ухоП = useRef(null);
  const векоПол = useRef(null);
  const векоЗакр = useRef(null);
  const поворот = useRef(null);

  /* Всё живое состояние кошки держим здесь: это обычный
     объект, его изменение не перерисовывает страницу */
  const жизнь = useRef({
    x: null,
    сторона: -1,          // -1 влево, +1 вправо
    режим: "сидит",       // «сидит» или «идёт»
    шаги: null,
    показан: null,
    картинки: {},
    следующееМорганье: 1.5,
    морганье: -1,
    двойноеМорганье: false,
    следующееУхо: 2,
    ухо: -1,
    стороннееУхо: "П",
    размахУха: 12,
    двойноеУхо: false,
    следующийВзмах: 4,
    взмах: -1,
  });

  useEffect(() => {
    const ж = жизнь.current;
    const площадка = сцена.current;
    const слой = поворот.current;
    if (!площадка || !слой) return;

    /* Если человек просил систему «поменьше движения»,
       кошка просто сидит: без прыжков и морганий. */
    const тихо = window.matchMedia(
      "(prefers-reduced-motion: reduce)"
    ).matches;

    /* Каждый кадр — своя картинка, загруженная заранее.
       Менять адрес у одной картинки нельзя: пока новый кадр
       грузится, старый успевает растянуться и мигнуть. */
    Object.keys(КАДРЫ).forEach((имя) => {
      const кар = document.createElement("img");
      кар.src = asset(`/images/cat/${имя}.webp`);
      кар.alt = "";
      кар.draggable = false;
      Object.assign(кар.style, {
        position: "absolute",
        bottom: "0",
        imageRendering: "pixelated",
        visibility: "hidden",
        /* Обязательно. По общему правилу сайта картинка не шире
           своего места (img { max-width: 100% }), а место здесь —
           точка без ширины. Без этой строки кадры ходьбы
           и прыжка сжимаются в ноль, и кошка пропадает,
           как только встаёт. */
        maxWidth: "none",
        maxHeight: "none",
      });
      слой.appendChild(кар);
      ж.картинки[имя] = кар;
    });

    let прошлое = performance.now();
    let заявка = 0;

    const шаг = (сейчас) => {
      тик(сейчас);
      заявка = requestAnimationFrame(шаг);
    };

    function тик(сейчас) {
      const дт = Math.min(0.05, (сейчас - прошлое) / 1000);
      прошлое = сейчас;
      const t = сейчас / 1000;
      const S = scale;
      const узел = кошка.current;
      if (!узел) return;

      const ширинаСцены = площадка.clientWidth;
      if (ж.x === null) ж.x = начальноеМесто(ширинаСцены, S);

      let кадр = "sit_0";
      let высотаПрыжка = 0;

      if (ж.режим === "идёт") {
        const о = ж.шаги;
        о.t += дт * 1000;
        while (о.i < о.список.length && о.t >= о.список[о.i].д) {
          const ш = о.список[о.i];
          о.t -= ш.д;
          if (ш.dx) о.x0 += ж.сторона * ш.dx;
          о.i++;
        }
        if (о.i >= о.список.length) {
          ж.x = о.x0;
          ж.режим = "сидит";
          ж.шаги = null;
        } else {
          const ш = о.список[о.i];
          const p = о.t / ш.д;
          кадр = ш.ф;
          ж.x =
            о.x0 +
            (ш.dx
              ? ж.сторона * ш.dx * (ш.дуга ? плавно(p) * 0.3 + p * 0.7 : p)
              : 0);
          if (ш.дуга) {
            const а = ш.дуга[0] + (ш.дуга[1] - ш.дуга[0]) * p;
            высотаПрыжка = Math.sin(Math.PI * а) * о.подъём;
          }
        }
      }

      /* Положение округляем до целых точек: на дробных
         пиксельная картинка начинает дрожать */
      узел.style.left = Math.round(ж.x) + "px";
      узел.style.transform = `translateY(${-Math.round(высотаПрыжка)}px)`;

      if (ж.режим === "сидит") {
        рисоватьСидя(t, дт, S);
      } else {
        рисоватьКадр(кадр, S, высотаПрыжка);
      }
    }

    /* ---------- КОШКА СИДИТ ----------
       Здесь она собрана из слоёв: хвост, тело, два уха
       и два века. Слои поворачиваются по отдельности —
       так получается, что она живая, а не замерла. */
    function рисоватьСидя(t, дт, S) {
      const рама = каркас.current;
      if (ж.показан) {
        ж.картинки[ж.показан].style.visibility = "hidden";
        ж.показан = null;
      }
      рама.style.display = "block";
      const ф = КАДРЫ.sit_0;
      рама.style.left = Math.round(-ф.cx * S) + "px";
      рама.style.width = Math.round(ф.ш * S) + "px";
      рама.style.height = Math.round(ф.в * S) + "px";

      const т = тень.current;
      т.style.width = 70 * S + "px";
      т.style.left = -30 * S + "px";
      т.style.transform = "none";

      if (тихо) return;

      /* Хвост: медленно качается, иногда дёргает */
      if (t > ж.следующийВзмах && ж.взмах < 0) ж.взмах = 0;
      let дёрг = 0;
      if (ж.взмах >= 0) {
        ж.взмах += дт;
        const p = ж.взмах / 0.7;
        if (p >= 1) {
          ж.взмах = -1;
          ж.следующийВзмах = t + 2.5 + Math.random() * 4;
        } else {
          дёрг = Math.sin(p * Math.PI) * -22;
        }
      }
      /* Угол округляем до шага в 4 градуса: на плавном
         повороте пиксели начинают переливаться */
      const уголХвоста =
        Math.round(
          (-5 + 7 * Math.sin(t * 1.5) + 3 * Math.sin(t * 3.7) + дёрг) / 4
        ) * 4;
      хвост.current.style.transformOrigin = `${69 * S}px ${124 * S}px`;
      хвост.current.style.transform = `rotate(${уголХвоста}deg)`;

      /* Уши: раз в пару секунд дёргается одно из двух */
      if (t > ж.следующееУхо && ж.ухо < 0) {
        ж.ухо = 0;
        ж.стороннееУхо = Math.random() < 0.5 ? "Л" : "П";
        ж.размахУха = 9 + Math.random() * 8;
        ж.двойноеУхо = Math.random() < 0.35;
      }
      let уЛ = 0;
      let уП = 0;
      if (ж.ухо >= 0) {
        ж.ухо += дт;
        const длина = ж.двойноеУхо ? 0.5 : 0.26;
        const p = ж.ухо / длина;
        if (p >= 1) {
          ж.ухо = -1;
          ж.следующееУхо = t + 1.8 + Math.random() * 3.5;
        } else {
          const в =
            Math.abs(Math.sin(p * Math.PI * (ж.двойноеУхо ? 2 : 1))) *
            ж.размахУха;
          if (ж.стороннееУхо === "Л") уЛ = -в;
          else уП = в;
        }
      }
      уЛ = Math.round(уЛ / 5) * 5;
      уП = Math.round(уП / 5) * 5;
      ухоЛ.current.style.transformOrigin = `${20 * S}px ${17 * S}px`;
      ухоЛ.current.style.transform = `rotate(${уЛ}deg)`;
      ухоП.current.style.transformOrigin = `${50 * S}px ${17 * S}px`;
      ухоП.current.style.transform = `rotate(${уП}deg)`;

      /* Морганье: веко приспускается, закрывается, поднимается */
      if (t > ж.следующееМорганье && ж.морганье < 0) {
        ж.морганье = 0;
        ж.двойноеМорганье = Math.random() < 0.25;
      }
      let веко = 0;
      if (ж.морганье >= 0) {
        ж.морганье += дт;
        const одно = 0.2;
        const всего = ж.двойноеМорганье ? 0.48 : одно;
        let б = ж.морганье;
        if (ж.двойноеМорганье && б > 0.28) б -= 0.28;
        else if (ж.двойноеМорганье && б > одно) б = одно;
        веко = б < 0.05 ? 1 : б < 0.14 ? 2 : б < одно ? 1 : 0;
        if (ж.морганье >= всего) {
          ж.морганье = -1;
          ж.следующееМорганье = t + 2.2 + Math.random() * 4;
        }
      }
      векоПол.current.style.opacity = веко === 1 ? 1 : 0;
      векоЗакр.current.style.opacity = веко === 2 ? 1 : 0;
    }

    /* ---------- КОШКА ИДЁТ ИЛИ ПРЫГАЕТ ----------
       Здесь показывается готовый кадр целиком, а слои
       прячутся. */
    function рисоватьКадр(кадр, S, высотаПрыжка) {
      каркас.current.style.display = "none";
      const ф = КАДРЫ[кадр];
      const кар = ж.картинки[кадр];
      кар.style.width = Math.round(ф.ш * S) + "px";
      кар.style.height = Math.round(ф.в * S) + "px";
      кар.style.left = Math.round(-ф.cx * S) + "px";
      if (ж.показан !== кадр) {
        if (ж.показан) ж.картинки[ж.показан].style.visibility = "hidden";
        кар.style.visibility = "visible";
        ж.показан = кадр;
      }
      /* Все кадры нарисованы мордой влево. Чтобы идти вправо,
         слой отражается зеркально. */
      слой.style.transform = ж.сторона === 1 ? "scaleX(-1)" : "none";

      const т = тень.current;
      const ширина =
        (кадр.startsWith("walk") || кадр.startsWith("jump") ? 110 : 75) *
        S *
        (1 - Math.min(0.5, высотаПрыжка / (200 * S)));
      т.style.width = ширина + "px";
      т.style.left = -ширина / 2 + "px";
      т.style.transform = `translateY(${высотаПрыжка}px)`;
    }

    заявка = requestAnimationFrame(шаг);
    return () => {
      cancelAnimationFrame(заявка);
      Object.values(ж.картинки).forEach((к) => к.remove());
      ж.картинки = {};
      ж.показан = null;
    };
  }, [scale]);

  /* ---------- НАЖАТИЕ ---------- */
  const нажали = () => {
    const ж = жизнь.current;
    const площадка = сцена.current;
    if (!площадка || ж.режим !== "сидит") return;

    const S = scale;
    const W = площадка.clientWidth;
    const полеХодьбы = поле(W, S, ШИРИНА_ХОДЬБЫ);
    const полеПрыжка = поле(W, S, ШИРИНА_ПРЫЖКА);
    const середина = W / 2;

    const прыгает = Math.random() < jumpChance;

    if (прыгает) {
      /* Прыжок: если места в стороне нет, кошка подпрыгивает
         на месте — выглядит не хуже, чем с перелётом */
      const dx = Math.min(70 * S, полеПрыжка);
      /* Высота прыжка подстраивается под полоску: в низкой
         кошка подпрыгивает пониже, но макушку не срезает.
         105 — это кадр прыжка плюс небольшой запас. */
      const подъём = Math.min(
        75 * S,
        Math.max(24, площадка.clientHeight - 105)
      );
      let сторона = ж.сторона;
      if (ж.x + сторона * dx < середина - полеПрыжка) сторона = -сторона;
      else if (ж.x + сторона * dx > середина + полеПрыжка) сторона = -сторона;
      запустить(
        [
          { ф: "sit_3", д: 110 },
          { ф: "sit_4", д: 130 },
          { ф: "jump_0", д: 260 },
          { ф: "jump_1", д: 110, dx: dx * 0.15, дуга: [0, 0.3] },
          { ф: "jump_2", д: 260, dx: dx * 0.55, дуга: [0.3, 0.75] },
          { ф: "jump_3", д: 120, dx: dx * 0.2, дуга: [0.75, 1] },
          { ф: "jump_4", д: 130, dx: dx * 0.1 },
          { ф: "jump_5", д: 240 },
          { ф: "sit_4", д: 220 },
          { ф: "sit_3", д: 160 },
        ],
        сторона,
        подъём
      );
      return;
    }

    /* Прогулка. Длина — сколько просили, но не больше,
       чем помещается. */
    const путь = Math.max(16, Math.min(walkDistance, полеХодьбы * 2));
    let сторона = -1;
    if (ж.x - путь < середина - полеХодьбы) сторона = 1;
    if (сторона === 1 && ж.x + путь > середина + полеХодьбы) сторона = -1;

    const держать = 150;
    const скорость = walkSpeed * S;
    const шагов = Math.max(
      4,
      Math.round(путь / ((скорость * держать) / 1000))
    );
    const список = [
      { ф: "sit_3", д: 150 },
      { ф: "sit_4", д: 220 },
    ];
    for (let i = 0; i < шагов; i++) {
      /* Первые и последние два шага — медленнее: так она
         трогается и останавливается, а не телепортируется */
      const доля = i < 2 ? 0.6 : i >= шагов - 2 ? 0.7 : 1;
      список.push({
        ф: `walk_${i % 6}`,
        д: держать,
        dx: ((скорость * держать) / 1000) * доля,
      });
    }
    список.push({ ф: "sit_4", д: 320 }, { ф: "sit_3", д: 200 });
    запустить(список, сторона);
  };

  const запустить = (список, сторона, подъём = 0) => {
    const ж = жизнь.current;
    ж.сторона = сторона;
    ж.режим = "идёт";
    ж.шаги = { список, i: 0, t: 0, x0: ж.x, подъём };
  };

  const слои = [
    ["cat_tail", хвост],
    ["cat_body", null],
    ["cat_earL", ухоЛ],
    ["cat_earR", ухоП],
    ["cat_lid_half", векоПол],
    ["cat_lid_closed", векоЗакр],
  ];

  return (
    <div className={s.stage} ref={сцена}>
      <button
        type="button"
        className={s.cat}
        ref={кошка}
        onClick={нажали}
        aria-label={label}
      >
        <span className={s.shadow} ref={тень} aria-hidden="true" />

        {/* Слои сидящей кошки: хвост, тело, уши, веки */}
        <span className={s.rig} ref={каркас} aria-hidden="true">
          {слои.map(([имя, ссылка]) => (
            <img
              key={имя}
              ref={ссылка}
              src={asset(`/images/cat/${имя}.webp`)}
              alt=""
              draggable="false"
              className={`${s.layer} ${
                имя.startsWith("cat_lid") ? s.lid : ""
              }`}
            />
          ))}
        </span>

        {/* Сюда складываются кадры ходьбы и прыжка */}
        <span className={s.flip} ref={поворот} aria-hidden="true" />
      </button>
    </div>
  );
}
