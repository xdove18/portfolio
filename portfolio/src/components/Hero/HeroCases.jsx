import { useEffect, useMemo, useRef, useState } from "react";
import { useNavigate } from "react-router-dom";
import { projects } from "../../data/projects";
import { asset } from "../../utils/asset";
import { thumb } from "../Case/imagePath";
import s from "./HeroCases.module.css";

/* ============================================================
   МОЗАИКА ЭКРАНОВ НА ПЕРВОМ ЭКРАНЕ
   ============================================================
   Справа от заголовка — сетка плиток с настоящими экранами
   из проектов: карточки товара, трекер привычек, CRM риелтора.
   Не карточки с описанием кейса, а сама работа.

   Плитки живут: каждая время от времени меняет экран на
   следующий, с мягким перетеканием. Меняются по очереди, по
   одной — поэтому мозаика «дышит», а не мигает целиком.

   Прокрутка первого экрана листает мозаику быстрее: чем ниже
   человек спускается, тем больше работ он успевает увидеть
   ещё до раздела «Проекты».

   Нажатие на плитку открывает кейс, из которого этот экран.
   ============================================================ */

/* Рисунок сетки: сколько строк занимает каждая плитка.
   2 — высокая, 1 — обычная. Всего получается 4 ряда по 3
   колонки. Менять можно свободно: сумма должна делиться на 3. */
const ПЛИТКИ = [2, 1, 2, 2, 1, 2, 1, 1];

/* Как часто меняется ОДНА плитка, в миллисекундах.
   Плитки меняются по очереди, так что полный круг занимает
   это число, умноженное на количество плиток. */
const ШАГ = 1400;

export default function HeroCases() {
  const navigate = useNavigate();
  const боксРеф = useRef(null);

  /* ---------- Собираем экраны из всех кейсов ----------
     По очереди из каждого проекта: первый экран первого кейса,
     первый экран второго и так далее. Благодаря этому соседние
     плитки показывают разные проекты, а не один подряд. */
  const пул = useMemo(() => {
    const очереди = projects
      .filter((p) => !p.comingSoon)
      .map((p) => ({
        проект: p,
        экраны: (p.screenGroups || []).flatMap((g) => g.screens || []),
      }))
      .filter((q) => q.экраны.length > 0);

    const итог = [];
    const самая = Math.max(...очереди.map((q) => q.экраны.length), 0);

    for (let i = 0; i < самая; i += 1) {
      for (const q of очереди) {
        if (q.экраны[i]) {
          итог.push({
            src: q.экраны[i],
            slug: q.проект.slug,
            title: q.проект.title,
          });
        }
      }
    }

    return итог;
  }, []);

  /* Общий сдвиг. Растёт сам по таймеру и от прокрутки —
     он же двигает все плитки вперёд по их очередям. */
  const [сдвиг, setСдвиг] = useState(0);

  /* Какая плитка меняется прямо сейчас. Ходит по кругу,
     чтобы они не прыгали все разом. */
  const [очередьПлитки, setОчередьПлитки] = useState(0);

  const сдвигОтПрокрутки = useRef(0);

  // ---------- Смена по таймеру ----------
  useEffect(() => {
    if (пул.length === 0) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

    const таймер = setInterval(() => {
      setОчередьПлитки((n) => {
        const следующая = (n + 1) % ПЛИТКИ.length;
        // Круг замкнулся — сдвигаем все очереди на шаг вперёд
        if (следующая === 0) setСдвиг((v) => v + 1);
        return следующая;
      });
    }, ШАГ);

    return () => clearInterval(таймер);
  }, [пул.length]);

  // ---------- Ускорение от прокрутки ----------
  useEffect(() => {
    if (пул.length === 0) return;

    function приПрокрутке() {
      const бокс = боксРеф.current;
      if (!бокс) return;

      const экран = бокс.closest("section") || бокс;
      const r = экран.getBoundingClientRect();
      if (r.bottom < 0 || r.top > window.innerHeight) return;

      /* Насколько пролистан первый экран: 0 — только зашли,
         1 — пролистали целиком. */
      const пройдено = Math.min(
        Math.max(-r.top / (r.height || window.innerHeight), 0),
        1
      );

      // За весь первый экран мозаика прокручивается на три круга
      const шагов = Math.floor(пройдено * ПЛИТКИ.length * 3);

      if (шагов !== сдвигОтПрокрутки.current) {
        const разница = шагов - сдвигОтПрокрутки.current;
        сдвигОтПрокрутки.current = шагов;
        setСдвиг((v) => v + разница);
      }
    }

    /* passive: true — обещание браузеру, что мы не мешаем
       прокрутке. Благодаря этому она остаётся плавной. */
    window.addEventListener("scroll", приПрокрутке, { passive: true });
    return () => window.removeEventListener("scroll", приПрокрутке);
  }, [пул.length]);

  if (пул.length === 0) return null;

  return (
    <div className={s.wrap} ref={боксРеф}>
      <div className={s.mosaic}>
        {ПЛИТКИ.map((высота, i) => {
          /* У каждой плитки своя очередь экранов: берём каждый
             восьмой, начиная со своего номера. Так две плитки
             никогда не показывают один и тот же экран. */
          const своя = пул.filter((_, k) => k % ПЛИТКИ.length === i);
          if (своя.length === 0) return null;

          // Плитка, до которой очередь ещё не дошла, стоит на месте
          const шаг = сдвиг + (i <= очередьПлитки ? 1 : 0);

          return (
            <Tile
              key={i}
              очередь={своя}
              шаг={шаг}
              высота={высота}
              onOpen={(slug) => navigate(`/projects/${slug}`)}
            />
          );
        })}
      </div>
    </div>
  );
}

/* ------------------------------------------------------------
   ОДНА ПЛИТКА
   ------------------------------------------------------------
   Внутри лежат две картинки друг на друге. Видна всегда одна,
   вторая ждёт своей очереди. Когда приходит время сменить
   экран, новый кладётся в невидимую картинку, и они плавно
   меняются местами — отсюда мягкое перетекание вместо рывка.
   ------------------------------------------------------------ */
function Tile({ очередь, шаг, высота, onOpen }) {
  const номер = ((шаг % очередь.length) + очередь.length) % очередь.length;
  const текущий = очередь[номер];

  /* Состояние одной записью: две картинки и то, какая из них
     сейчас сверху. Одной записью — чтобы при смене нельзя было
     случайно прочитать половину старого состояния. */
  const [вид, setВид] = useState({ a: текущий, b: null, aСверху: true });

  /* Пришёл новый экран — кладём его в ту картинку, которая
     сейчас скрыта. Показывать пока НЕ переключаем: картинка
     ещё не загрузилась, и на её месте мелькнула бы пустота.
     Переключение происходит ниже, когда картинка готова. */
  useEffect(() => {
    setВид((прошлое) => {
      const видимая = прошлое.aСверху ? прошлое.a : прошлое.b;
      if (видимая && видимая.src === текущий.src) return прошлое;

      return прошлое.aСверху
        ? { ...прошлое, b: текущий }
        : { ...прошлое, a: текущий };
    });
    /* В списке зависимостей только адрес картинки. Сам объект
       «текущий» пересоздаётся при каждой перерисовке, и смена
       запускалась бы без причины. */
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [текущий.src]);

  /* Картинка загрузилась. Если это та самая скрытая, которую
     мы ждали, — меняем их местами: теперь она сверху. */
  function приЗагрузке(место) {
    setВид((прошлое) => {
      const скрытоеМесто = прошлое.aСверху ? 1 : 0;
      if (место !== скрытоеМесто) return прошлое;

      const скрытая = место === 0 ? прошлое.a : прошлое.b;
      if (!скрытая || скрытая.src !== текущий.src) return прошлое;

      return { ...прошлое, aСверху: !прошлое.aСверху };
    });
  }

  return (
    <button
      type="button"
      className={s.tile}
      style={{ gridRow: `span ${высота}` }}
      onClick={() => onOpen(текущий.slug)}
      aria-label={`Открыть кейс «${текущий.title}»`}
      /* Курсор над плиткой превращается в кольцо
         с надписью «нажми на меня» */
      data-cursor="image"
    >
      {[вид.a, вид.b].map((экран, i) =>
        экран ? (
          <img
            key={i}
            /* Лёгкая копия: плитка маленькая, полная версия
               здесь была бы лишним весом */
            src={asset(thumb(экран.src))}
            alt=""
            onLoad={() => приЗагрузке(i)}
            className={`${s.shot} ${
              (i === 0) === вид.aСверху ? s.shotOn : ""
            }`}
          />
        ) : null
      )}

      {/* Название проекта проступает при наведении */}
      <span className={s.caption}>{текущий.title}</span>
    </button>
  );
}
