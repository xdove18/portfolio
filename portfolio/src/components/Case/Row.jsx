import { fixHangingWords } from "../../utils/typography";
import s from "./Case.module.css";

/* ============================================================
   РЯД КЕЙСА: ПОДПИСЬ СЛЕВА, ТЕКСТ СПРАВА
   ============================================================
   Это единственная раскладка для текста на странице кейса.
   Любой абзац и любой список стоят в таком ряду:

     ЗАДАЧА      Переделать каталог так, чтобы запрос
                 на расчёт можно было оставить с любой
                 страницы.

   Слева короткая подпись, справа узкая колонка текста.
   Ширины берутся из общих переменных (--label, --label-gap,
   --read-case в файле src/styles/variables.css), поэтому все
   блоки на всех кейсах совпадают по ширине и текст везде
   начинается на одной вертикали.

   Подпись можно не писать — тогда слева останется пусто,
   а текст всё равно встанет в свою колонку. Так оформляются
   пояснения под картинками и таблицами.

   Картинки, схемы, видео и таблицы в такой ряд НЕ ставятся:
   они идут во всю ширину колонки. На этом и держится
   страница — узкий текст рядом с большими картинками.
   ============================================================ */

export default function Row({ label, children }) {
  return (
    <div className={s.row}>
      {label ? (
        <h3 className={s.rowLabel}>{fixHangingWords(label)}</h3>
      ) : (
        /* Пустая клетка, чтобы текст остался в своей колонке */
        <div aria-hidden="true" />
      )}

      <div className={s.rowBody}>{children}</div>
    </div>
  );
}
