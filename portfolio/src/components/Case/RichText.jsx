import { fixHangingWords } from "../../utils/typography";
import s from "./Case.module.css";

/* ============================================================
   ТЕКСТ С ВЫДЕЛЕНИЯМИ
   ============================================================
   Позволяет подсвечивать важные места прямо в текстах кейса,
   чтобы страница не читалась сплошным полотном.

   Как пользоваться в файле src/data/projects.js:

   **жирный**   — важная мысль, выделяется тёмным жирным
   ==маркер==   — самое главное, подсвечивается жёлтым

   Пример:
   "Бизнес теряет **до 30% выручки** из-за возвратов,
    основная причина — ==ошибка в выборе размера==."

   Обычный текст без звёздочек продолжает работать как раньше,
   ничего переписывать не нужно.

   Заодно здесь расставляются неразрывные пробелы, чтобы
   короткие предлоги не повисали в конце строки — см.
   src/utils/typography.js.
   ============================================================ */

export default function RichText({ children }) {
  if (typeof children !== "string") return children ?? null;

  return <>{parse(children)}</>;
}

/* Знаки, которые нельзя оставлять снаружи подсветки */
const ЗНАКИ = [",", ".", ";", ":", "!", "?", "»"];

/* Разбираем строку на куски: обычный текст, **жирный**, ==маркер== */
function parse(text) {
  // Скобки в выражении нужны, чтобы разделители тоже попали в результат
  const parts = text.split(/(\*\*[^*]+\*\*|==[^=]+==)/g);

  /* Запятую или точку сразу после выделения забираем внутрь
     подсветки. У подсветки есть собственное поле по краям,
     и знак, оставшийся снаружи, отъезжал от слова — выглядело
     это как лишний пробел перед запятой. */
  for (let i = 0; i < parts.length - 1; i += 1) {
    const маркер = parts[i].startsWith("==") && parts[i].endsWith("==");
    if (!маркер) continue;

    const следующий = parts[i + 1];
    if (!следующий || !ЗНАКИ.includes(следующий[0])) continue;

    parts[i] = parts[i].slice(0, -2) + следующий[0] + "==";
    parts[i + 1] = следующий.slice(1);
  }

  return parts.map((part, i) => {
    if (part.startsWith("**") && part.endsWith("**")) {
      return (
        <strong className={s.accentStrong} key={i}>
          {fixHangingWords(part.slice(2, -2))}
        </strong>
      );
    }

    if (part.startsWith("==") && part.endsWith("==")) {
      return (
        <mark className={s.accentMark} key={i}>
          {fixHangingWords(part.slice(2, -2))}
        </mark>
      );
    }

    return fixHangingWords(part);
  });
}
