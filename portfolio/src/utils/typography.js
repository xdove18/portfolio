/* ============================================================
   ТИПОГРАФИКА: УБИРАЕМ ВИСЯЩИЕ ПРЕДЛОГИ
   ============================================================
   Висящий предлог — это когда короткое слово («в», «на», «и»,
   «с», «по») остаётся в конце строки, а то, к чему оно
   относится, переносится на следующую:

       …покупатель уходит на
       оформлении заказа

   Читается это плохо и выглядит неаккуратно. По правилам
   русской типографики такие слова нельзя отрывать от
   следующего за ними.

   Чинится неразрывным пробелом — это обычный пробел, который
   браузеру запрещено превращать в перенос строки. Выглядит он
   точно так же, просто склеивает два слова в одно целое.

   Эта функция расставляет такие пробелы сама. Ничего в текстах
   помечать не нужно — тексты в projects.js и site.js пишутся
   как обычно.
   ============================================================ */

/* Неразрывный пробел. Выглядит как обычный, но строка по нему
   не переносится. */
const НЕРАЗРЫВНЫЙ = " ";

export function fixHangingWords(text) {
  if (typeof text !== "string" || !text) return text;

  let результат = text;

  /* 1. Короткие слова (1–3 буквы) приклеиваем к следующему.
        Это предлоги, союзы и частицы: в, на, из, по, и, а,
        но, до, от, за, к, с, у, о, не, ни, что, так, как.

        Слово должно стоять в начале строки или после пробела,
        скобки, кавычки — чтобы не цеплять окончания длинных
        слов. Звёздочка и знак равенства в списке потому, что
        ими в текстах помечаются выделения: **жирный**
        и ==маркер==.

        Проход делаем трижды. Почему не один раз: если короткие
        слова идут подряд («а не по догадкам»), за один проход
        склеится только первое — поиск уже стоит в середине
        строки и не видит пробела перед вторым. Три прохода
        покрывают любые реальные цепочки. */
  for (let проход = 0; проход < 3; проход += 1) {
    результат = результат.replace(
      /(^|[\s(«"„*=])([a-zA-Zа-яёА-ЯЁ]{1,3})[ \t]+/g,
      `$1$2${НЕРАЗРЫВНЫЙ}`
    );
  }

  return (
    результат
      /* 2. Тире не должно начинать строку — приклеиваем его
            к предыдущему слову. */
      .replace(/\s+([—–])\s/g, `${НЕРАЗРЫВНЫЙ}$1 `)

      /* 3. Число и единица измерения тоже не разделяются:
            «15 млн», «30 %», «2 недели». */
      .replace(/(\d)[ \t]+([a-zA-Zа-яёА-ЯЁ%₽])/g, `$1${НЕРАЗРЫВНЫЙ}$2`)
  );
}

/* ------------------------------------------------------------
   ТО ЖЕ САМОЕ, НО СРАЗУ ДЛЯ ВСЕХ ТЕКСТОВ
   ------------------------------------------------------------
   Проходит по всему содержимому файла с текстами и приводит в
   порядок каждую строку. Благодаря этому правило работает
   везде само, и его не нужно вспоминать при написании нового текста.

   Адреса файлов и ссылки не трогаем: в них пробелов нет,
   но на всякий случай пропускаем их явно.
   ------------------------------------------------------------ */
export function fixHangingWordsDeep(значение) {
  if (typeof значение === "string") {
    if (значение.startsWith("/") || значение.startsWith("http")) return значение;
    return fixHangingWords(значение);
  }

  if (Array.isArray(значение)) return значение.map(fixHangingWordsDeep);

  if (значение && typeof значение === "object") {
    const результат = {};
    for (const ключ of Object.keys(значение)) {
      результат[ключ] = fixHangingWordsDeep(значение[ключ]);
    }
    return результат;
  }

  return значение;
}
