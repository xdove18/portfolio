/* ============================================================
   ЗАПРЕТ ПРОКРУТКИ СТРАНИЦЫ
   ============================================================
   Нужен, когда поверх страницы открыто окно: просмотр экрана,
   схема на весь экран, заставка. Пока окно открыто, фон под
   ним не должен ездить.

   Почему это вынесено в отдельный файл, а не написано на месте.

   Раньше каждое окно само писало странице «не прокручивайся»
   и само же потом отменяло. Пока окно одно — всё хорошо.
   Но стоило открыть два подряд (например, меню, а из него
   перейти к просмотру экрана), как одно из них отменяло запрет
   раньше времени — или, наоборот, запрет оставался висеть
   после закрытия.

   А оставшийся запрет — это не мелочь: пока он висит, у
   страницы перестаёт работать прилипание, и шапка больше не
   держится наверху при прокрутке. Выглядит как поломка сайта,
   а причина совсем в другом месте.

   Поэтому здесь ведётся счёт: сколько окон сейчас просят
   тишины. Запрет снимается только когда закрылось последнее.
   ============================================================ */

let сколькоОкон = 0;
let былоЗначение = "";

export function lockScroll() {
  // Первое окно — запоминаем, как было, и запрещаем прокрутку
  if (сколькоОкон === 0) {
    былоЗначение = document.body.style.overflow;
    document.body.style.overflow = "hidden";
  }

  сколькоОкон += 1;
}

export function unlockScroll() {
  // Math.max на случай лишнего вызова — счёт не уйдёт в минус
  сколькоОкон = Math.max(0, сколькоОкон - 1);

  // Закрылось последнее окно — возвращаем всё как было
  if (сколькоОкон === 0) {
    document.body.style.overflow = былоЗначение;
  }
}
