import { site } from "../data/site";

/* ============================================================
   ЗАГРУЗКА ЯНДЕКС МЕТРИКИ
   ============================================================
   Счётчик подключается ТОЛЬКО после того, как человек нажал
   «Принять» в баннере про куки. До этого на сайте не появляется
   ни одного запроса к Яндексу и ни одной его куки — именно
   этого требует закон.

   Номер счётчика лежит в src/data/site.js, поле metrikaId.
   Пока оно пустое, здесь ничего не происходит: сайт работает
   как обычно, аналитики просто нет.

   Как подключить Метрику:
   1) заведите счётчик на metrika.yandex.ru
   2) впишите его номер в site.js в поле metrikaId
   Всё остальное уже готово.
   ============================================================ */

/* Чтобы не подключить счётчик дважды, если функцию вызовут
   повторно — например, человек нажал «Принять» на второй
   вкладке */
let ужеЗагружена = false;

export function загрузитьМетрику() {
  const номер = site.metrikaId;

  if (!номер || ужеЗагружена) return;
  if (typeof window === "undefined") return;

  ужеЗагружена = true;
  window.METRIKA_ID = номер;

  /* Это официальный код счётчика Яндекса, записанный
     понятнее. Он создаёт очередь window.ym: пока файл
     счётчика грузится, вызовы копятся в ней, а потом
     отправляются все разом. */
  window.ym =
    window.ym ||
    function (...аргументы) {
      (window.ym.a = window.ym.a || []).push(аргументы);
    };
  window.ym.l = Date.now();

  const скрипт = document.createElement("script");
  скрипт.async = true;
  скрипт.src = "https://mc.yandex.ru/metrika/tag.js";
  document.head.appendChild(скрипт);

  window.ym(номер, "init", {
    /* Карта кликов и записи сеансов намеренно выключены:
       они собирают заметно больше данных о человеке, чем
       нужно для обычной статистики посещений. */
    clickmap: false,
    webvisor: false,
    trackLinks: true,
    accurateTrackBounce: true,
  });
}
