/* ============================================================
   АДРЕС ФАЙЛА НА САЙТЕ
   ============================================================
   Зачем это нужно.

   В файле projects.js все картинки и видео записаны от корня:
   "/images/projects/habits/screen-01.webp". Пока сайт лежит
   в корне домена — всё сходится.

   Но на GitHub Pages сайт лежит не в корне, а во вложенной
   папке: xdove18.github.io/portfolio/. И тогда адрес
   "/images/..." указал бы мимо — на xdove18.github.io/images/,
   где ничего нет. Картинки просто не открылись бы.

   Эта функция подставляет к адресу нужное начало. Само начало
   задаётся один раз в файле vite.config.js, в строке BASE.

   Пользоваться так:
   <img src={asset(project.cover)} />
   ============================================================ */

export function asset(path) {
  if (!path) return path;

  // Ссылки на чужие сайты и уже готовые адреса не трогаем
  if (/^(https?:)?\/\//.test(path) || path.startsWith("data:")) return path;

  /* BASE_URL — это то самое начало адреса. На вашем компьютере
     оно равно "/", на GitHub Pages — "/portfolio/". */
  const base = import.meta.env.BASE_URL;

  // Начало уже подставлено — второй раз не добавляем
  if (base !== "/" && path.startsWith(base)) return path;

  const хвост = path.startsWith("/") ? path : "/" + path;

  // base заканчивается косой чертой, хвост с неё начинается —
  // убираем лишнюю, чтобы не получилось двух подряд
  return base.replace(/\/$/, "") + хвост;
}
