/* ============================================================
   ПРОВЕРКА КАЧЕСТВА ИНТЕРНЕТА
   ============================================================
   Одно место, где решается вопрос «человек сейчас на плохой
   связи или нет». Этим пользуются и обложки проектов на
   главной, и демо-видео внутри кейсов — чтобы правило было
   одинаковым и правилось в одном файле.

   Осторожность здесь намеренная. Браузер определяет скорость
   очень приблизительно и часто занижает её даже на быстром
   интернете. Поэтому «плохой связью» считаем только два явных
   случая: человек сам включил экономию трафика, либо сеть
   действительно очень медленная (2G).
   ============================================================ */
export function isSlowNetwork() {
  const net = navigator.connection;
  if (!net) return false;

  if (net.saveData) return true;

  return ["slow-2g", "2g"].includes(net.effectiveType);
}
