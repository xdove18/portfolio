/* ============================================================
   СОГЛАСИЕ НА АНАЛИТИКУ
   ============================================================
   Одно место, где хранится ответ человека на вопрос про куки.

   Возможных ответов три:

   "yes"   — согласился, аналитику можно загружать
   "no"    — отказался, грузим только то, без чего сайт
             не работает
   null    — ещё не отвечал, нужно показать баннер

   Ответ лежит в памяти браузера и переживает закрытие вкладки.
   Если память недоступна — например, человек сидит в режиме
   инкогнито, — сайт не ломается: просто спросим ещё раз
   в следующий заход.
   ============================================================ */

const КЛЮЧ = "cookie-consent";

export function прочитатьСогласие() {
  try {
    const ответ = localStorage.getItem(КЛЮЧ);
    return ответ === "yes" || ответ === "no" ? ответ : null;
  } catch {
    /* Чтение запрещено — считаем, что человек ещё не отвечал */
    return null;
  }
}

export function записатьСогласие(ответ) {
  try {
    localStorage.setItem(КЛЮЧ, ответ);
  } catch {
    /* Запомнить не вышло — спросим в следующий раз.
       Сам выбор при этом уже применён. */
  }
}
